             from pg_class c left join pg_index i on i.indrelid = c.oid and i.indisreplident left join pg_class ic on ic.oid = i.indexrelid
            where c.relnamespace = 'public'::regnamespace and c.relkind = 'r';"
# Chaque séquence par ce qui la possède (i: identité, a: serial, seule:<nom>) et ses paramètres.
