// Le DDL de scripts/schema-executable.js : ses ETAPES, telles quelles, interrogées
// par psql au lieu de l'API de gestion, assemblées comme main() les assemble.
const { execFileSync } = require("child_process");
const [generateur, hote, port, base] = process.argv.slice(2);
const { ETAPES } = require(generateur);
const out = ["begin;", ""];
for (const e of ETAPES) {
  let lignes;
  try {
    const txt = execFileSync("psql", ["-h", hote, "-p", port, "-U", "postgres", "-d", base, "-X", "-tA", "-q", "-v", "ON_ERROR_STOP=1",
      "-c", `select coalesce(json_agg(t), '[]') from (${e.sql}) t`], { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });
    lignes = e.rendu(JSON.parse(txt.trim()));
  } catch (err) {
    process.stderr.write(`étape « ${e.titre} » : ${String(err.stderr || err.message).trim()}\n`);
    process.exit(1);
  }
  out.push(`-- ${e.titre} (${lignes.length})`, lignes.length ? lignes.join("\n\n") : "--   (aucun objet)", "");
}
out.push("commit;", "");
process.stdout.write(out.join("\n"));
