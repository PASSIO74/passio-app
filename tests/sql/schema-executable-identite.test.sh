cat > "$OUTILS/recharger.js" <<'JS'
// Les lignes de la source reversées dans la cible COMME restaurer-donnees.js les
// reverse (`chargerTable`) : le TEXTE de chaque ligne tel quel (NDJSON), les clés
// seules lues par JSON.parse, `ordreInsert` du module (triggers utilisateur coupés,
// liste de colonnes explicite, `overriding system value`), puis SON recalage des
// séquences — lu dans sa source, puisqu'il n'est pas exporté : s'il change de
// forme, le banc le dit.
// ⚠️ Jamais `JSON.stringify(JSON.parse(…))` sur une ligne : un entier au-delà de
// 2^53 (le `rid` de 63 bits d'une version de travail de R25 ; la finale en a 53)
// y est ARRONDI au double le plus proche —
// mesuré : 2906581903110193585 → 2906581903110193700, et deux rid distincts
// deviennent le même, que l'index unique refuse.
const fs = require("fs");
const { execFileSync } = require("child_process");
const [restaurer, hote, port, source, cible, ...tables] = process.argv.slice(2);
const { ordreInsert } = require(restaurer);
const psql = (base, sql) => execFileSync("psql", ["-h", hote, "-p", port, "-U", "postgres", "-d", base, "-X", "-tA", "-q", "-v", "ON_ERROR_STOP=1"],
  { input: sql, encoding: "utf8", stdio: ["pipe", "pipe", "pipe"] });
const m = fs.readFileSync(restaurer, "utf8").match(/await sql\(ctx, `(do \$\$ declare r record; m bigint; begin[\s\S]*?end loop; end \$\$;)`\);/);
if (!m) { console.error("recalage des séquences introuvable dans restaurer-donnees.js : le banc ne sait plus le rejouer"); process.exit(1); }
try {
  for (const t of tables) {
    const lignes = psql(source, `select to_jsonb(x)::text from public."${t}" x;`).split("\n").filter(Boolean);
    if (!lignes.length) continue;
    const presentes = new Set(psql(cible, `select column_name from information_schema.columns where table_schema='public' and table_name='${t}';`).trim().split("\n"));
    const cles = new Set();
    for (const l of lignes) for (const k of Object.keys(JSON.parse(l))) cles.add(k);
    // La clé primaire de la CIBLE, cible du conflit, comme `clesPrimaires` du
    // module (vérification finale de R25, 2026-11-04).
    const pk = psql(cible, `select a.attname from pg_index i join lateral unnest(i.indkey::int2[]) with ordinality k(attnum, rang) on true
      join pg_attribute a on a.attrelid = i.indrelid and a.attnum = k.attnum where i.indrelid = 'public."${t}"'::regclass and i.indisprimary order by k.rang;`).trim().split("\n").filter(Boolean);
    psql(cible, ordreInsert(t, [...cles].filter((k) => presentes.has(k)), "[" + lignes.join(",") + "]", pk));
  }
  psql(cible, m[1]);
} catch (err) { console.error(String(err.stderr || err.message).trim()); process.exit(1); }
console.log("rechargé");
