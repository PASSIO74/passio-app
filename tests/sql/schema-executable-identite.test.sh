                                from pg_depend dep join pg_class t on t.oid = dep.refobjid
                                join pg_attribute a on a.attrelid = dep.refobjid and a.attnum = dep.refobjsubid
                               where dep.classid = 'pg_class'::regclass and dep.objid = s.oid and dep.deptype in ('i', 'a')
                                 and dep.refclassid = 'pg_class'::regclass), 'seule:' || s.relname) d,
                    format_type(q.seqtypid, null) || ',' || q.seqstart || ',' || q.seqincrement p
