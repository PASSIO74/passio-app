#!/usr/bin/env bash
# ═══════════════════════════════════════════════════════════════════════════
# BANC — scripts/schema-executable.js : ce qu'une RECONSTRUCTION rend de
# l'identité de réplication et des séquences (revue indépendante du
# 2026-11-03, risque R25).
#
# Le DDL que la sauvegarde nocturne range dans chaque archive (`schema.sql`,
# .github/workflows/sauvegarde.yml) et qu'une reprise applique à une base VIDE
# (`restaurer-donnees.js --schema`) est rendu ICI par les ETAPES du dépôt,
# exécutées contre une base SOURCE jetable par psql au lieu de l'API de
# gestion : même SQL de catalogue, même rendu, même `begin; … commit;`. Aucune
# étape n'est sautée — une requête qui échoue fait échouer le banc.
#
# La source porte ce que la production porte ou portera (canal ①, 2026-11-04) —
# les DEUX formes qu'a prises migration_realtime_identite_opaque_2026-11-03 (la
# finale, sha256 9f48ffe1…, est appliquée en production depuis le 2026-11-04) ;
# le banc ne dépend pas du fichier de la migration lui-même :
#   · `membres` — la première : `rid bigint generated by default as identity`,
#     index unique `membres_rid_key`, `replica identity using index`, garde
#     `trg_rid_opaque`, séquence SANS droit pour anon/authenticated ;
#   · `aimes` — la seconde, FINALE : `rid bigint not null` ALÉATOIRE sur 53 bits
#     (défaut tiré de `gen_random_uuid()`, chiffres 17 à 32, masque 2^53 − 1, à
#     l'octet près de la migration), index unique `aimes_rid_key`, même identité de
#     réplication, garde recopiée de `rid_opaque_garde` — ni identité, ni séquence ;
#   · `interactions` en FULL (comment_interactions jusqu'au 2026-11-04), `brouillons`
#     en NOTHING, `orpheline` en USING INDEX dont l'index a été supprimé ;
#   · `journal` — identité ALWAYS aux droits par défaut de Supabase (`rwU`),
#     comme client_errors.id et migrations_appliquees.id ;
#   · `renommee` — identité d'une table RENOMMÉE : sa séquence garde l'ancien
#     nom, c'est pourquoi une séquence d'identité se désigne par sa colonne ;
#   · `erreurs` — un `bigserial` aux droits choisis ; `compteur_seq` — une
#     séquence autonome aux droits choisis.
#
#   ⓪ la source est bien ce qu'on croit (sinon le banc ne prouverait rien) ;
#   ① le DDL rendu s'applique à une base VIDE aux droits par défaut de Supabase ;
#   ② identité de réplication identique, table par table ;
#   ③ une seule séquence par colonne d'identité, aucune `*_seq1`, mêmes
#      paramètres, le `serial` rattaché à sa colonne ;
#   ④ mêmes droits de séquence pour anon / authenticated — et ce qu'ils valent ;
#   ⑤ les lignes reversées COMME `restaurer-donnees.js` les reverse
#      (`ordreInsert` du module, recalage des séquences lu dans sa source) :
#      contenu identique, puis une insertion de plus passe sur chaque table ;
#   ⑥ ce qu'un DELETE publie sur la base reconstruite (décodage logique
#      `test_decoding`) : `rid` seul pour `membres`, la ligne pour `interactions` ;
#   ⑦ rejoué sur la base semée : rien ne casse, rien ne se double ; une cible
#      qui a DÉRIVÉ (identité, droits) revient à la source.
#
#   bash tests/sql/schema-executable-identite.test.sh
#
# Rouge prouvé le 2026-11-04 sur le générateur d'origin/main (3e4019d, worktree
# privé) : 25 ✅ 15 ❌ — toutes les tables en DEFAULT, des séquences orphelines
# et deux `*_seq1`, le `serial` détaché, `rwU` partout (authenticated recule la
# séquence de rid), « duplicate key … erreurs_pkey » après la reprise, et les
# DELETE de `membres` et d'`aimes` qui republient `conv_id` / `post_id`, `user_id`.
# Prérequis : PostgreSQL 14+ (binaires serveur, `test_decoding`), Node 18+.
# Ne touche AUCUNE base réelle.
# ═══════════════════════════════════════════════════════════════════════════
set -euo pipefail

RACINE="$(cd "$(dirname "$0")/../.." && pwd)"
GENERATEUR="$RACINE/scripts/schema-executable.js"
RESTAURER="$RACINE/scripts/restaurer-donnees.js"
PGBIN="$(ls -d /usr/lib/postgresql/*/bin 2>/dev/null | sort -V | tail -1 || true)"
[ -n "$PGBIN" ] && PATH="$PGBIN:$PATH"

command -v initdb >/dev/null || { echo "❌ binaires serveur PostgreSQL introuvables"; exit 1; }
command -v node >/dev/null || { echo "❌ node introuvable"; exit 1; }
[ -f "$GENERATEUR" ] || { echo "❌ générateur introuvable : $GENERATEUR"; exit 1; }
[ -f "$RESTAURER" ] || { echo "❌ restaurer-donnees.js introuvable : $RESTAURER"; exit 1; }

PORT=$(( 6600 + RANDOM % 100 ))
if [ "$(id -u)" -eq 0 ]; then
  id pgbanc >/dev/null 2>&1 || useradd -m pgbanc >/dev/null 2>&1
  BASE="$(su pgbanc -c 'mktemp -d -p ~')"
  SU="su pgbanc -c"
else
  BASE="$(mktemp -d)"
  SU="bash -c"
fi
OUTILS="$(mktemp -d)"
lancer() { $SU "PATH='$PATH' $*"; }
nettoyer() { lancer "pg_ctl -D '$BASE/data' stop -m immediate" >/dev/null 2>&1; rm -rf "$BASE" "$OUTILS"; }
trap nettoyer EXIT

lancer "initdb -D '$BASE/data' -A trust -U postgres" >/dev/null 2>&1
lancer "pg_ctl -D '$BASE/data' -o \"-k $BASE -p $PORT -c listen_addresses= -c wal_level=logical -c max_replication_slots=4\" -l '$BASE/pg.log' start" >/dev/null 2>&1
demarre=0
for _ in $(seq 1 30); do
  psql -h "$BASE" -p "$PORT" -U postgres -X -c "select 1" >/dev/null 2>&1 && { demarre=1; break; }
  sleep 0.5
done
if [ "$demarre" -ne 1 ]; then
  echo "❌ le serveur PostgreSQL de test n'a pas démarré — aucun résultat n'est exploitable"
  [ -f "$BASE/pg.log" ] && tail -5 "$BASE/pg.log"
  exit 1
fi

# `SQL <base> <requête>` : une valeur, erreurs comprises (jamais d'arrêt du banc).
SQL()  { psql -h "$BASE" -p "$PORT" -U postgres -d "$1" -X -tA -q -v ON_ERROR_STOP=1 -c "$2" 2>&1; }
ok=0; ko=0
verifier() { if [ "$2" = "$3" ]; then ok=$((ok+1)); printf '  ✅ %s\n' "$1"; else ko=$((ko+1)); printf '  ❌ %s\n     attendu : %s\n     obtenu  : %s\n' "$1" "$2" "$3"; fi; }
contient() { if printf '%s' "$3" | grep -qi -- "$2"; then ok=$((ok+1)); printf '  ✅ %s\n' "$1"; else ko=$((ko+1)); printf '  ❌ %s\n     motif attendu : %s\n     obtenu : %s\n' "$1" "$2" "$3"; fi; }

# ── Un projet Supabase NEUF : rôles, auth.uid(), droits par défaut de `public`
# (pg_default_acl du propriétaire postgres : `rwU` sur toute séquence neuve,
# EXECUTE sur toute fonction neuve, tout sur toute table neuve), seaux et cron
# vides, publication `supabase_realtime` vide. La source et la cible en partent.
psql -h "$BASE" -p "$PORT" -U postgres -X -q -v ON_ERROR_STOP=1 -c "create role anon; create role authenticated; create role service_role;" >/dev/null
projet_neuf() {
  psql -h "$BASE" -p "$PORT" -U postgres -X -q -v ON_ERROR_STOP=1 -c "create database $1" >/dev/null
  psql -h "$BASE" -p "$PORT" -U postgres -d "$1" -X -q -v ON_ERROR_STOP=1 >/dev/null <<'SQL'
create schema auth;
create function auth.uid() returns uuid language sql stable as
  $fn$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $fn$;
grant usage on schema public to anon, authenticated, service_role;
grant usage on schema auth to anon, authenticated, service_role;
grant execute on function auth.uid() to anon, authenticated, service_role;
alter default privileges in schema public grant all on tables to anon, authenticated, service_role;
alter default privileges in schema public grant all on sequences to anon, authenticated, service_role;
alter default privileges in schema public grant all on functions to anon, authenticated, service_role;
create schema storage;
create table storage.buckets (id text primary key, name text not null, public boolean default false, file_size_limit bigint);
create schema cron;
create table cron.job (jobid bigint primary key, jobname text, schedule text, command text);
create publication supabase_realtime;
SQL
}
projet_neuf source
projet_neuf reprise

psql -h "$BASE" -p "$PORT" -U postgres -d source -X -q -v ON_ERROR_STOP=1 >/dev/null <<'SQL'
-- ① La forme R25 : rid opaque, index unique sur lui seul, identité de réplication,
-- garde (copie de public.rid_opaque_garde), séquence sans droit client.
create table public.membres (conv_id text not null, user_id text not null,
  rid bigint generated by default as identity, primary key (conv_id, user_id));
create unique index membres_rid_key on public.membres (rid);
alter table public.membres replica identity using index membres_rid_key;
create function public.rid_garde()
returns trigger
language plpgsql
security definer
set search_path to ''
as $fn$
begin
  if tg_op = 'INSERT' then
    new.rid := pg_catalog.nextval(pg_catalog.pg_get_serial_sequence(pg_catalog.format('%I.%I', tg_table_schema, tg_table_name), 'rid')::regclass);
  else
    new.rid := old.rid;
  end if;
  return new;
end
$fn$;
revoke all on function public.rid_garde() from public, anon, authenticated;
create trigger trg_rid_opaque before insert or update of rid on public.membres
  for each row execute function public.rid_garde();
do $$ begin execute format('revoke all on sequence %s from anon, authenticated', pg_get_serial_sequence('public.membres', 'rid')); end $$;
alter table public.membres enable row level security;
create policy membres_lecture on public.membres for select to authenticated using (user_id = (select auth.uid())::text);

